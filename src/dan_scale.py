def points_to_raw(points):
    return POINTS_C * math.expm1(points / POINTS_A) if points > 0 else 0.0


def to_dan(raw):
    if not raw > 0:
        return 0.0
    x = (math.log(raw) - DAN_LNR0) / DAN_STEP
    last = len(DAN_KNOT) - 1
    if x <= 0:
        return DAN_KNOT[0] + DAN_SLOPE_LO * DAN_STEP * x
    if x >= last:
        return DAN_KNOT[-1] + DAN_SLOPE_HI * DAN_STEP * (x - last)
    i = int(x)
    f = x - i
    return DAN_KNOT[i] + f * (DAN_KNOT[i + 1] - DAN_KNOT[i])
